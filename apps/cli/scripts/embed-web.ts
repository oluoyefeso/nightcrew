// Generates src/web-assets.gen.ts: one `with { type: "file" }` import per built
// dashboard file, so `bun build --compile` embeds the whole dashboard.

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const dist = join(import.meta.dir, "../../web/dist");
const out = join(import.meta.dir, "../src/web-assets.gen.ts");

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

let files: string[];
try {
  files = walk(dist);
} catch {
  console.error("apps/web/dist is missing. Build the dashboard first: bun run --filter @nightcrew/web build");
  process.exit(1);
}

const lines = files.map(
  (f, i) => `import f${i} from ${JSON.stringify(relative(join(import.meta.dir, "../src"), f))} with { type: "file" };`,
);
const map = files.map((f, i) => `  ${JSON.stringify(`/${relative(dist, f)}`)}: f${i},`);
writeFileSync(
  out,
  `// @ts-nocheck\n// Generated by scripts/embed-web.ts for the compiled binary. Do not edit.\n${lines.join("\n")}\n\nexport default {\n${map.join("\n")}\n} as Record<string, string>;\n`,
);
console.log(`Embedded ${files.length} dashboard files.`);
